  async function adminResults() {
    const [rows, classes, enr, mods] = await Promise.all([
      q(sb.from('attempts').select('id, user_id, module_id, score, total, passed, submitted_at, profiles(full_name, matric, category, institution), modules(title)').not('submitted_at', 'is', null).order('submitted_at', { ascending: false }).limit(10000)),
      q(sb.from('classes').select('id, name').order('created_at')),
      q(sb.from('enrollments').select('user_id, class_id')),
      q(sb.from('modules').select('id, title').order('title')),
    ]);
    const html = `
      <div class="row" style="margin-bottom:14px">
        <select id="cls" style="width:auto;margin:0"><option value="">All classes</option>${classes.map((c) => `<option value="${c.id}">${esc(c.name)}</option>`).join('')}</select>
        <select id="mod" style="width:auto;margin:0"><option value="">All modules</option>${mods.map((m) => `<option value="${m.id}">${esc(m.title)}</option>`).join('')}</select>
        <label class="check" style="margin:0"><input type="checkbox" id="bestonly"><span>Best attempt per person</span></label>
        <button class="btn quiet" id="csv" style="margin-left:auto">Export CSV</button>
      </div>
      <div id="sum" class="grid" style="margin-bottom:16px"></div>
      <div id="list"></div>`;
    return {
      html, bind(el) {
        const cls = el.querySelector('#cls'), mod = el.querySelector('#mod'), bestonly = el.querySelector('#bestonly');
        let current = [];
        const draw = () => {
          const inClass = cls.value ? new Set(enr.filter((e) => e.class_id === cls.value).map((e) => e.user_id)) : null;
          let list = rows.filter((r) => (!inClass || inClass.has(r.user_id)) && (!mod.value || r.module_id === mod.value));
          if (bestonly.checked) {
            const b = {};
            list.forEach((r) => { const k = r.user_id + r.module_id; if (!b[k] || pct(r.score, r.total) > pct(b[k].score, b[k].total)) b[k] = r; });
            list = Object.values(b);
          }
          current = list;
          const people = new Set(list.map((r) => r.user_id)).size;
          const passRate = list.length ? Math.round((list.filter((r) => r.passed).length / list.length) * 100) : 0;
          const avg = list.length ? Math.round(list.reduce((s, r) => s + pct(r.score, r.total), 0) / list.length) : 0;
          el.querySelector('#sum').innerHTML = [['Attempts', list.length], ['People', people], ['Pass rate', passRate + '%'], ['Average score', avg + '%']]
            .map(([l, v]) => `<div class="card" style="padding:16px"><div class="muted small">${l}</div><div style="font-family:Fraunces,Georgia,serif;font-size:28px;font-weight:600">${v}</div></div>`).join('');
          el.querySelector('#list').innerHTML = `<div class="table-wrap"><table>
            <tr><th>Date</th><th>Name</th><th>Matric</th><th>Category</th><th>Module</th><th>Score</th><th>Result</th></tr>
            ${list.slice(0, 1000).map((r) => `<tr><td class="small">${fmtDateTime(r.submitted_at)}</td><td>${esc(r.profiles?.full_name || '')}</td><td>${esc(r.profiles?.matric || '')}</td>
              <td class="small">${esc(r.profiles?.category || '')}</td><td>${esc(r.modules?.title || '')}</td><td>${r.score}/${r.total} (${pct(r.score, r.total)}%)</td>
              <td>${r.passed ? '<span class="pill ok">pass</span>' : '<span class="pill bad">fail</span>'}</td></tr>`).join('') || '<tr><td colspan="7" class="muted">No results yet.</td></tr>'}
          </table></div>${list.length > 1000 ? '<p class="muted small">Showing the latest 1000 — export CSV for all.</p>' : ''}`;
        };
        cls.onchange = mod.onchange = bestonly.onchange = draw; draw();
        el.querySelector('#csv').onclick = () => downloadCSV(`results-${new Date().toISOString().slice(0, 10)}.csv`,
          ['Date', 'Name', 'Matric/Staff no', 'Category', 'Institution', 'Module', 'Score', 'Total', 'Percent', 'Result'],
          current.map((r) => [fmtDateTime(r.submitted_at), r.profiles?.full_name, r.profiles?.matric, r.profiles?.category, r.profiles?.institution,
            r.modules?.title, r.score, r.total, pct(r.score, r.total), r.passed ? 'Pass' : 'Fail']));
      },
    };
  }

