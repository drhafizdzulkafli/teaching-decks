  // Question import: rows of  Question | A | B | C | D | (E…) | Correct letter | (Explanation)
  function parseCSV(t) {
    const rows = []; let row = [], f = '', inQ = false;
    for (let i = 0; i < t.length; i++) {
      const c = t[i];
      if (inQ) { if (c === '"') { if (t[i + 1] === '"') { f += '"'; i++; } else inQ = false; } else f += c; }
      else if (c === '"') inQ = true;
      else if (c === ',') { row.push(f); f = ''; }
      else if (c === '\n') { row.push(f); rows.push(row); row = []; f = ''; }
      else f += c;
    }
    row.push(f); rows.push(row); return rows;
  }
  function parseQuestions(text) {
    text = text.replace(/\r/g, '').trim();
    if (!text) return { items: [], errors: [] };
    const rows = text.includes('\t') ? text.split('\n').map((l) => l.split('\t')) : parseCSV(text);
    const items = [], errors = [];
    rows.forEach((r, n) => {
      const cells = r.map((x) => x.trim());
      while (cells.length && !cells[cells.length - 1]) cells.pop();
      if (!cells.length) return;
      if (n === 0 && /^question/i.test(cells[0])) return; // header row
      const isL = (s) => /^[A-H]$/i.test(s || '');
      let ans, expl = '', opts;
      if (isL(cells[cells.length - 1])) { ans = cells[cells.length - 1]; opts = cells.slice(1, -1); }
      else if (isL(cells[cells.length - 2])) { ans = cells[cells.length - 2]; expl = cells[cells.length - 1]; opts = cells.slice(1, -2); }
      else { errors.push(`Row ${n + 1}: cannot find the correct-answer letter (A–H).`); return; }
      while (opts.length && !opts[opts.length - 1]) opts.pop();
      const idx = ans.toUpperCase().charCodeAt(0) - 65;
      if (!cells[0]) errors.push(`Row ${n + 1}: question text is empty.`);
      else if (opts.length < 2) errors.push(`Row ${n + 1}: needs at least 2 options.`);
      else if (opts.some((o) => !o)) errors.push(`Row ${n + 1}: an option in the middle is empty.`);
      else if (idx >= opts.length) errors.push(`Row ${n + 1}: answer ${ans.toUpperCase()} but only ${opts.length} options.`);
      else items.push({ stem: cells[0], options: opts, answer: idx, explanation: expl || null });
    });
    return { items, errors };
  }

